//! RESEARCH ONLY. The application host owns this bounded registry, not the client.
//! Shutdown requests stop but does not destroy uncertain keepers. Polling native
//! observations is NOT promised bounded against a stuck kernel call. No Drop
//! shortcut: scope destruction still needs proof or an external identified owner.
use optic_bridge_core::JobId;
use std::io;

pub(super) trait Keeper {
    fn identity(&self) -> &JobId;
    fn request_stop(&self);
    fn observe(&mut self) -> io::Result<bool>;
}

struct Entry<K> {
    keeper: K,
    observation_errors: u32,
    last_error: Option<io::ErrorKind>,
}

#[derive(Debug, PartialEq, Eq)]
pub(super) enum AdmissionError {
    Closing,
    Capacity,
    Prepare(io::ErrorKind),
    Duplicate,
}

#[derive(Debug, PartialEq, Eq)]
pub(super) struct Snapshot {
    pub root: JobId,
    pub closing: bool,
    pub retained: usize,
    pub observation_errors: u32,
    pub complete: bool,
}

#[must_use = "application owns the root until proof; shutdown does not consume Pending"]
pub(super) struct PendingRoot<K: Keeper> {
    id: JobId,
    capacity: usize,
    closing: bool,
    entries: Vec<Entry<K>>,
    completed_errors: u32,
}

impl<K: Keeper> PendingRoot<K> {
    pub fn new(capacity: usize) -> Self {
        assert!((1..=64).contains(&capacity));
        Self {
            id: JobId::generate().unwrap(),
            capacity,
            closing: false,
            entries: Vec::with_capacity(capacity),
            completed_errors: 0,
        }
    }

    // Capacity checked BEFORE preparing a keeper. The fixture prepares only
    // reservations/handles here and starts native children through get_mut later.
    pub fn prepare(
        &mut self,
        build: impl FnOnce() -> io::Result<K>,
    ) -> Result<JobId, AdmissionError> {
        if self.closing {
            return Err(AdmissionError::Closing);
        }
        if self.entries.len() == self.capacity {
            return Err(AdmissionError::Capacity);
        }
        let keeper = build().map_err(|e| AdmissionError::Prepare(e.kind()))?;
        // Identity is generated by the trusted preparation, not supplied by the
        // caller. Duplicate rejection must NOT destroy an already-live keeper:
        // preparation has not launched effects in this research contract.
        if self
            .entries
            .iter()
            .any(|e| e.keeper.identity() == keeper.identity())
        {
            return Err(AdmissionError::Duplicate);
        }
        let id = keeper.identity().clone();
        self.entries.push(Entry {
            keeper,
            observation_errors: 0,
            last_error: None,
        });
        Ok(id)
    }

    pub fn get_mut(&mut self, id: &JobId) -> Option<&mut K> {
        self.entries
            .iter_mut()
            .find(|e| e.keeper.identity() == id)
            .map(|e| &mut e.keeper)
    }

    // Only signals; no native call, polling, join or destruction. Same root stays
    // at the same address and retains all capacity under repeated shutdowns.
    pub fn request_shutdown(&mut self) -> Snapshot {
        self.closing = true;
        for entry in &self.entries {
            entry.keeper.request_stop();
        }
        self.snapshot()
    }

    pub fn observe_pass(&mut self) -> Snapshot {
        let mut index = 0;
        while index < self.entries.len() {
            let entry = &mut self.entries[index];
            match entry.keeper.observe() {
                Ok(true) => {
                    self.completed_errors = self
                        .completed_errors
                        .saturating_add(entry.observation_errors);
                    self.entries.swap_remove(index);
                }
                Ok(false) => {
                    index += 1;
                }
                Err(error) => {
                    entry.observation_errors = entry.observation_errors.saturating_add(1);
                    entry.last_error = Some(error.kind());
                    // Error is not completion; keep the SAME owner and budgets.
                    index += 1;
                }
            }
        }
        self.snapshot()
    }

    pub fn snapshot(&self) -> Snapshot {
        Snapshot {
            root: self.id.clone(),
            closing: self.closing,
            retained: self.entries.len(),
            observation_errors: self.entries.iter().fold(self.completed_errors, |n, e| {
                n.saturating_add(e.observation_errors)
            }),
            complete: self.closing && self.entries.is_empty(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::{
        Arc,
        atomic::{AtomicBool, AtomicUsize, Ordering},
    };
    struct Fixed {
        id: JobId,
        stop: Arc<AtomicBool>,
        done: Arc<AtomicBool>,
        drops: Arc<AtomicUsize>,
        fail: bool,
    }
    impl Keeper for Fixed {
        fn identity(&self) -> &JobId {
            &self.id
        }
        fn request_stop(&self) {
            self.stop.store(true, Ordering::Release);
        }
        fn observe(&mut self) -> io::Result<bool> {
            if self.fail {
                Err(io::Error::other("fixed observation fault"))
            } else {
                Ok(self.done.load(Ordering::Acquire))
            }
        }
    }
    impl Drop for Fixed {
        fn drop(&mut self) {
            self.drops.fetch_add(1, Ordering::AcqRel);
        }
    }
    fn fixed() -> Fixed {
        Fixed {
            id: JobId::generate().unwrap(),
            stop: Arc::new(AtomicBool::new(false)),
            done: Arc::new(AtomicBool::new(false)),
            drops: Arc::new(AtomicUsize::new(0)),
            fail: false,
        }
    }
    #[test]
    fn full_root_never_invokes_preparation_and_keeps_pending_on_shutdown() {
        let mut root = PendingRoot::new(1);
        let owner = fixed();
        let drops = Arc::clone(&owner.drops);
        let id = root.prepare(|| Ok(owner)).unwrap();
        assert_eq!(
            root.prepare(|| panic!("capacity must reject before effects")),
            Err(AdmissionError::Capacity)
        );
        let before = root.snapshot().root;
        for _ in 0..3 {
            let state = root.request_shutdown();
            assert_eq!(state.root, before);
            assert!(!state.complete && state.retained == 1);
            assert_eq!(drops.load(Ordering::Acquire), 0);
            assert!(!root.observe_pass().complete);
        }
        assert_eq!(
            root.prepare(|| panic!("closed root must reject preparation")),
            Err(AdmissionError::Closing)
        );
        root.get_mut(&id)
            .unwrap()
            .done
            .store(true, Ordering::Release);
        assert!(root.observe_pass().complete);
        assert_eq!(drops.load(Ordering::Acquire), 1);
    }
    #[test]
    fn repeated_observation_errors_retain_identity_and_do_not_drop_owner() {
        let mut root = PendingRoot::new(1);
        let mut owner = fixed();
        owner.fail = true;
        let drops = Arc::clone(&owner.drops);
        let id = root.prepare(|| Ok(owner)).unwrap();
        root.request_shutdown();
        for errors in 1..=4 {
            let state = root.observe_pass();
            assert_eq!(state.observation_errors, errors);
            assert_eq!(state.retained, 1);
            assert!(!state.complete);
            assert_eq!(root.get_mut(&id).unwrap().identity(), &id);
            assert_eq!(drops.load(Ordering::Acquire), 0);
        }
        let owner = root.get_mut(&id).unwrap();
        owner.fail = false;
        owner.done.store(true, Ordering::Release);
        assert!(root.observe_pass().complete);
        assert_eq!(drops.load(Ordering::Acquire), 1);
        assert_eq!(root.snapshot().observation_errors, 4);
    }
    #[test]
    fn preparation_error_leaves_capacity_available_and_empty_is_not_closed() {
        let mut root = PendingRoot::new(1);
        assert!(!root.snapshot().complete);
        assert_eq!(
            root.prepare(|| Err(io::Error::other("fixed prepare fault"))),
            Err(AdmissionError::Prepare(io::ErrorKind::Other))
        );
        let id = root.prepare(|| Ok(fixed())).unwrap();
        root.get_mut(&id)
            .unwrap()
            .done
            .store(true, Ordering::Release);
        assert_eq!(root.observe_pass().retained, 0);
        assert!(!root.snapshot().complete);
        assert!(root.request_shutdown().complete);
    }
}
